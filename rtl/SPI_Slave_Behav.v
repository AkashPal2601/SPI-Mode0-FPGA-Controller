`timescale 1ns/1ps
`define FPGA_DEBUG

module SPI_Slave_Behav (MISO,MOSI,SCLK,SS_n,clk,rst_n
`ifdef FPGA_DEBUG
    ,
    dbg_Slave_tx_reg,
    dbg_Slave_rx_reg
`endif
);

// total 2 fast clk cycle delay between SCLK edge detection of master and slave 

// defining SPI Operation Mode
parameter CPOL = 1'b0;
parameter CPHA = 1'b0;
//

parameter DATA_WIDTH = 8; // 8 bit data to be exchanged

// defining the FSM Controller States below
parameter STATE_IDLE = 2'b00; // default IDLE, inactive state of the Slave Module
parameter STATE_TRANSMIT = 2'b01; // full duplex data transmission between Master and Slave takes place here
parameter STATE_COMPUTE = 2'b10; // Performs computations on the data received from Master, to transmit new data back


input wire MOSI;  // Master Out Slave In pin to receive bits from the Master
input wire SCLK;  // SPI Clock generated by the Master
input wire SS_n;  // Slave Select pin (Active LOW)
input wire clk;   // fast, system clock
input wire rst_n; // asynchronouys reset signal

(* mark_debug = "true" *) output wire MISO; // Master In Slave Out pin to transmit data over to the Master
assign MISO = (!SS_n_sync_2)? tx_shift_reg[DATA_WIDTH-1] : 1'bz; ///// MISO pin is tri-stated when Slave is inactive

// FPGA Debug Output Pin Declaration
`ifdef FPGA_DEBUG
    output wire [DATA_WIDTH-1:0] dbg_Slave_tx_reg;
    output wire [DATA_WIDTH-1:0] dbg_Slave_rx_reg;
    assign dbg_Slave_tx_reg = tx_shift_reg;
    assign dbg_Slave_rx_reg = rx_shift_reg;
`endif
//

// Internal Nets and Registers used inside the Slave Module
//reg [2:1] SCLK_sync; // an array of 2 FFs, acting as a 2 FF Synchronizer for the SCLK input
reg SCLK_sync_1;
reg SCLK_sync_2;

//reg [2:1] SS_n_sync; // an array of 2 FFs, acting as a 2 FF Synchronizer for SS_n input
reg SS_n_sync_1;
reg SS_n_sync_2;


(* mark_debug = "true" *) reg [1:0] curr_state; // stores the current state of the FSM Controller
(* mark_debug = "true" *) reg [1:0] next_state; // stores the next state of the FSM Controller
reg [$clog2(DATA_WIDTH):0] bit_count; // counts the number of bits of data exchanged during STATE_TRANSMIT
(* mark_debug = "true" *) reg [DATA_WIDTH-1:0] tx_shift_reg; // transmitting shift register in the Slave Module
(* mark_debug = "true" *) reg [DATA_WIDTH-1:0] rx_shift_reg; // receiving shift register in the Slave Module

(* mark_debug = "true" *) reg compute_flag; // Active HIGH signal that indicates that the computation in STATE_COMPUTE is done
//

// SCLK Edge Detector Signals
wire SCLK_posedge = ((SCLK_sync_1) && !(SCLK_sync_2));
wire SCLK_negedge = (!(SCLK_sync_1) && (SCLK_sync_2));
//


// 2 Flip Flop Synchronizer for SCLK

always @(posedge clk or negedge rst_n)
begin
    if(!rst_n)
    begin
//        SCLK_sync <= {CPOL,CPOL};
        SCLK_sync_1 <= CPOL;
        SCLK_sync_2 <= CPOL;
    end
    else
    begin
        SCLK_sync_2 <= SCLK_sync_1;
        SCLK_sync_1 <= SCLK;
    end
end
//

// 2 Flip Flop Synchronizer for SS_n

always @(posedge clk or negedge rst_n)
begin
    if(!rst_n)
    begin

//        SS_n_sync <= {1'b1,1'b1}; // Slave deselected by default
        SS_n_sync_1 <= 1'b1;
        SS_n_sync_2 <= 1'b1;

    end
    else
    begin
        SS_n_sync_2 <= SS_n_sync_1;
        SS_n_sync_1 <= SS_n;
    end
end
//


// Next State Logic Block (Combinational)

always @(*) 
begin
    if(!rst_n) 
    begin
        next_state = STATE_IDLE; 
    end
    else
    begin
        case (curr_state)

        STATE_IDLE:
        begin
            if(!SS_n_sync_2)
            begin
                next_state = STATE_TRANSMIT;
            end
            else
            begin
                next_state = curr_state;
            end
        end

        STATE_TRANSMIT:
        begin
            if(SS_n_sync_2) // in case Master has suddenly pulled SS_n HIGH in between STATE TRANSMIT
            begin
                next_state = STATE_IDLE;
            end
            else if(bit_count == DATA_WIDTH)
            begin
                next_state = STATE_COMPUTE; // data exchange is completed
            end
            else
            begin
                next_state = curr_state;
            end
        end

        STATE_COMPUTE:
        begin
            if(SS_n_sync_2) // if SS_n pulled HIGH and Slave deactivated
            begin
                next_state = STATE_IDLE;
            end
            else
            begin
                next_state = curr_state;
            end
        end

        default:
        begin
            next_state = STATE_IDLE; 
        end

        endcase
    end

end
// Next State Logic Block ends

// Next State Register Loading (laying out the Flip Flops for the FSM)

always @(posedge clk or negedge rst_n)
begin
    if(!rst_n)
    begin
        curr_state <= STATE_IDLE;
    end
    else
    begin
        curr_state <= next_state;
    end
end
// Next State Register Loading ends


// State Operations

always @(posedge clk or negedge rst_n)
begin
    if(!rst_n)
    begin
        bit_count <= 0;
        tx_shift_reg <= 0;
        rx_shift_reg <= 0;
        compute_flag <= 1'b0;
    end
    else
    begin
        case (curr_state)

        STATE_IDLE:
        begin
            bit_count <= 0;
            compute_flag <= 1'b0; // cleared for next computation
        end

        STATE_TRANSMIT:
        begin
            if(SCLK_posedge) // Sample Operation
            begin
                rx_shift_reg <= {rx_shift_reg[DATA_WIDTH-2:0],MOSI}; // sampling in the MOSI bit at LSB
                bit_count <= bit_count + 1; // counting the number of bits sampled in
            end
            else if(SCLK_negedge) // Shift Operation
            begin
                tx_shift_reg <= {tx_shift_reg[DATA_WIDTH-2:0],1'b0}; // 1'b0 is a filler value
            end
            else
            begin
                
            end
        end

        STATE_COMPUTE: // we perform a simple and visible 1's complement on the input data from Master
        begin
            if(!compute_flag)
            begin
                tx_shift_reg <= ~(rx_shift_reg); // Computation on received data (1's complement in this case)
                compute_flag <= 1'b1;
            end
            else
            begin
                
            end
        end

        endcase


    end
end

endmodule

